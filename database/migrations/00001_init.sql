-- One database for everything. The pre-1.0 SQLite baseline is replaced as a
-- whole: the app has no production data, so there is no row migration to keep.
CREATE TABLE users (
    id text PRIMARY KEY,
    username text NOT NULL UNIQUE,
    public_key text NOT NULL,
    admin boolean NOT NULL DEFAULT false,
    -- Server-side retention of the ciphertext archive, in days. 0 is not a
    -- valid value: the archive is also the offline delivery buffer.
    retention_days integer NOT NULL DEFAULT 30
        CONSTRAINT users_retention_allowed CHECK (retention_days IN (7, 30, 90, 365))
);

-- A device is the unit of revocation: every token carries its id, so revoking
-- the row locks the device out immediately, not on the next token expiry.
CREATE TABLE devices (
    id text PRIMARY KEY,
    user_id text NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    label text NOT NULL,
    platform text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    last_seen_at timestamptz NOT NULL DEFAULT now(),
    revoked_at timestamptz
);

CREATE INDEX idx_devices_user ON devices (user_id);

-- Ciphertext archive. It is both history and the offline delivery buffer, so a
-- message is written here before it is handed to the recipient.
CREATE TABLE messages (
    id text PRIMARY KEY,
    seq bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL UNIQUE,
    -- Sorted "<a>|<b>" participant pair, so a conversation is one index range.
    conversation text NOT NULL,
    sender_id text NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    receiver_id text NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    content bytea,
    wrapped_key bytea,
    nonce bytea,
    mac bytea,
    sent_at timestamptz NOT NULL,
    expires_at timestamptz NOT NULL,
    -- A tombstone keeps the slot of a message whose ciphertext is gone.
    deleted_at timestamptz,
    -- A resent unacknowledged message must not become a second row.
    CONSTRAINT messages_sender_receiver_sent_at_key UNIQUE (sender_id, receiver_id, sent_at)
);

CREATE INDEX idx_messages_conversation ON messages (conversation, sent_at DESC, id DESC);
CREATE INDEX idx_messages_sender ON messages (sender_id);
CREATE INDEX idx_messages_expires ON messages (expires_at);

-- +goose Down
DROP TABLE IF EXISTS messages;
DROP TABLE IF EXISTS devices;
DROP TABLE IF EXISTS users;
