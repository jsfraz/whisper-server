-- +goose Up
-- Message lifecycle. Only an insert advances messages.seq, so a device that
-- already holds a row would never learn it was edited, deleted, reacted to or
-- pinned. Every such mutation appends here and is replayed by delta sync.
ALTER TABLE messages ADD COLUMN edited_at timestamptz;
-- Pins are shared between both participants, so the pin lives on the message
-- row rather than in a per-account table.
ALTER TABLE messages ADD COLUMN pinned_at timestamptz;
ALTER TABLE messages ADD COLUMN pinned_by text REFERENCES users (id) ON DELETE SET NULL;

CREATE TABLE message_events (
    event_seq bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Copies messages.id and messages.seq: an event may only be delivered to a
    -- device that already synced the message it talks about.
    message_id text NOT NULL REFERENCES messages (id) ON DELETE CASCADE,
    message_seq bigint NOT NULL,
    conversation text NOT NULL,
    sent_at timestamptz NOT NULL,
    kind text NOT NULL CONSTRAINT message_events_kind_allowed
        CHECK (kind IN ('edit', 'delete', 'reaction', 'pin')),
    actor_id text NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    -- Same layout as a message, so an edit or a reaction is opened with exactly
    -- the key material a message carries. NULL means "no reaction left".
    content bytea,
    wrapped_key bytea,
    nonce bytea,
    mac bytea,
    -- Only a pin event uses this: true pins, false unpins.
    pinned boolean,
    created_at timestamptz NOT NULL
);

CREATE INDEX idx_message_events_conversation ON message_events (conversation, event_seq);
CREATE INDEX idx_message_events_message ON message_events (message_id);
CREATE INDEX idx_messages_pinned ON messages (conversation, pinned_at DESC) WHERE pinned_at IS NOT NULL;

-- +goose Down
DROP INDEX IF EXISTS idx_messages_pinned;
DROP TABLE IF EXISTS message_events;
ALTER TABLE messages DROP COLUMN IF EXISTS pinned_by;
ALTER TABLE messages DROP COLUMN IF EXISTS pinned_at;
ALTER TABLE messages DROP COLUMN IF EXISTS edited_at;
